#!/usr/bin/env python3
"""Generate repeatable spell SQL from the shared client/server contract."""
import argparse
import csv
import decimal
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def literal(value):
    try:
        number = decimal.Decimal(value)
        if not number.is_finite():
            raise ValueError("non-finite number")
        return str(number)
    except decimal.InvalidOperation:
        return "'" + value.replace("'", "''") + "'"


def generate(path):
    with path.open(newline="") as source:
        rows = list(csv.DictReader(source, delimiter="\t"))
    if not rows or set(rows[0]) != {"id", "name", "base", "changes", "script", "note"}:
        raise ValueError("expected the six contract columns")
    ids = set()
    sql = ["-- Generated by sage/generate.py. Do not edit.",
           "-- Apply to the mangos database at client build 5875.",
           "DELETE FROM spell_template WHERE entry BETWEEN 40000 AND 40099;"]
    for row in rows:
        spell_id, base = int(row["id"]), int(row["base"])
        if not 40000 <= spell_id <= 40099 or spell_id in ids:
            raise ValueError(f"invalid or repeated id: {spell_id}")
        if not 0 < base < 40000:
            raise ValueError(f"invalid stock template: {base}")
        ids.add(spell_id)
        changes = {}
        for change in row["changes"].split(";"):
            field, value = change.split("=", 1)
            if not re.fullmatch(r"[a-zA-Z][a-zA-Z0-9_]*", field):
                raise ValueError(f"invalid field: {field}")
            if field in {"entry", "build", "name", "script_name"} or field in changes:
                raise ValueError(f"reserved or repeated field: {field}")
            changes[field] = value
        changes.update(entry=str(spell_id), build="5875", name=row["name"],
                       description=row["note"], auraDescription="",
                       script_name="" if row["script"] == "-" else row["script"])
        changes.setdefault("nameSubtext", "")
        sql.extend([f"\n-- {row['name']}",
                    "DROP TEMPORARY TABLE IF EXISTS sage_spell;",
                    "CREATE TEMPORARY TABLE sage_spell LIKE spell_template;",
                    f"INSERT INTO sage_spell SELECT * FROM spell_template WHERE entry = {base} AND build <= 5875 ORDER BY build DESC LIMIT 1;",
                    "UPDATE sage_spell SET " + ", ".join(f"`{key}` = {literal(value)}" for key, value in changes.items()) + ";",
                    "INSERT INTO spell_template SELECT * FROM sage_spell;"])
    sql.append("DROP TEMPORARY TABLE IF EXISTS sage_spell;")
    return "\n".join(sql) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target = ROOT / "sql/ascian/010-sage-spells.sql"
    result = generate(ROOT / "sage/spells.tsv")
    with (ROOT / "sage/ranks.tsv").open(newline="") as source:
        ranks = list(csv.DictReader(source, delimiter="\t"))
    dosis = [r for r in ranks if r["family"] == "Dosis"]
    passive = "\n".join([
        "-- Generated by sage/generate.py. Dosis rank 1 owns the passive.",
        "DELETE FROM spell_learn_spell WHERE entry BETWEEN 40000 AND 40099 AND SpellID = 40011;",
        "INSERT INTO spell_learn_spell (entry, SpellID, Active, build_min, build_max)",
        f"VALUES ({dosis[0]['id']}, 40011, 1, 5875, 5875);", ""])
    chain = ["-- Generated by sage/generate.py. Preserve the original spell ids.",
             "DELETE FROM spell_chain WHERE spell_id BETWEEN 40000 AND 40099;",
             "INSERT INTO spell_chain (spell_id, prev_spell, first_spell, rank, req_spell, build_min, build_max) VALUES"]
    chain.append(",\n".join(f"({r['id']}, {r['prev']}, {r['first']}, {r['rank']}, 0, 5875, 5875)"
                            for r in ranks if int(r["rank"]) > 0) + ";\n")
    header = ["// Generated by sage/generate.py from sage/ranks.tsv.", "#pragma once",
              "struct SageSpellLevel { uint32 spell; uint32 level; bool dosis; uint32 family; };",
              "static SageSpellLevel const sageSpellLevels[] = {"]
    header.extend(f"    {{{r['id']}, {r['level']}, {'true' if r['family'] == 'Dosis' else 'false'}, {r['first']}}},"
                  for r in ranks)
    header.extend(["};", "inline bool IsSageDosisSpell(uint32 id)", "{",
                   "    for (auto const& rank : sageSpellLevels)",
                   "        if (rank.dosis && rank.spell == id) return true;",
                   "    return false;", "}", ""])
    header.extend(["inline uint32 GetSageRankForLevel(uint32 id, uint32 level)", "{",
                   "    uint32 family = 0;",
                   "    for (auto const& rank : sageSpellLevels)",
                   "        if (rank.spell == id)", "        {",
                   "            if (rank.level <= level) return id;",
                   "            family = rank.family;", "        }",
                   "    if (!family) return id;", "    uint32 eligible = 0;",
                   "    for (auto const& rank : sageSpellLevels)",
                   "        if (rank.family == family && rank.level <= level) eligible = rank.spell;",
                   "    return eligible;", "}", ""])
    outputs = {target: result,
               ROOT / "sql/ascian/020-sage-passives.sql": passive,
               ROOT / "sql/ascian/030-sage-ranks.sql": "\n".join(chain),
               ROOT / "src/game/Spells/SageRanks.h": "\n".join(header)}
    if args.check:
        for path, content in outputs.items():
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f"generated file is stale: {path}; run sage/generate.py")
    else:
        for path, content in outputs.items():
            path.write_text(content)
