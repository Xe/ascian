#!/usr/bin/env python3
"""Generate repeatable spell SQL from the shared client/server contract."""
import argparse
import csv
import decimal
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def literal(value):
    try:
        number = decimal.Decimal(value)
        if not number.is_finite():
            raise ValueError("non-finite number")
        return str(number)
    except decimal.InvalidOperation:
        return "'" + value.replace("'", "''") + "'"


def generate(path):
    with path.open(newline="") as source:
        rows = list(csv.DictReader(source, delimiter="\t"))
    if not rows or set(rows[0]) != {"id", "name", "base", "changes", "script", "note"}:
        raise ValueError("expected the six contract columns")
    ids = set()
    sql = ["-- Generated by sage/generate.py. Do not edit.",
           "-- Apply to the mangos database at client build 5875.",
           "DELETE FROM spell_template WHERE entry BETWEEN 40000 AND 40099;"]
    for row in rows:
        spell_id, base = int(row["id"]), int(row["base"])
        if not 40000 <= spell_id <= 40099 or spell_id in ids:
            raise ValueError(f"invalid or repeated id: {spell_id}")
        if not 0 < base < 40000:
            raise ValueError(f"invalid stock template: {base}")
        ids.add(spell_id)
        changes = {}
        for change in row["changes"].split(";"):
            field, value = change.split("=", 1)
            if not re.fullmatch(r"[a-zA-Z][a-zA-Z0-9_]*", field):
                raise ValueError(f"invalid field: {field}")
            if field in {"entry", "build", "name", "script_name"} or field in changes:
                raise ValueError(f"reserved or repeated field: {field}")
            changes[field] = value
        changes.update(entry=str(spell_id), build="5875", name=row["name"],
                       nameSubtext="", description=row["note"], auraDescription="",
                       script_name="" if row["script"] == "-" else row["script"])
        sql.extend([f"\n-- {row['name']}",
                    "DROP TEMPORARY TABLE IF EXISTS sage_spell;",
                    "CREATE TEMPORARY TABLE sage_spell LIKE spell_template;",
                    f"INSERT INTO sage_spell SELECT * FROM spell_template WHERE entry = {base} AND build <= 5875 ORDER BY build DESC LIMIT 1;",
                    "UPDATE sage_spell SET " + ", ".join(f"`{key}` = {literal(value)}" for key, value in changes.items()) + ";",
                    "INSERT INTO spell_template SELECT * FROM sage_spell;"])
    sql.append("DROP TEMPORARY TABLE IF EXISTS sage_spell;")
    return "\n".join(sql) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target = ROOT / "sql/ascian/010-sage-spells.sql"
    result = generate(ROOT / "sage/spells.tsv")
    if args.check:
        if target.read_text() != result:
            raise SystemExit("generated SQL is stale; run sage/generate.py")
    else:
        target.write_text(result)
